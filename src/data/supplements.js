export const supplementsByCategory = (key) => SUPPLEMENTS.filter(s => s.category === key)

// Match supplements to the user's most recent blood panel. Returns entries the
// panel gives an actual reason to consider — never a generic upsell.
export function suggestFromBlood(latestTest, statusFor) {
  if (!latestTest?.values) return []
  const out = []
  for (const supp of SUPPLEMENTS) {
    for (const markerId of supp.bloodMarkers || []) {
      const value = latestTest.values[markerId]
      if (value == null) continue
      const status = statusFor(markerId, value)
      // Only a genuinely out-of-range marker justifies a suggestion.
      if (status === 'low' || status === 'high') {
        out.push({ supplement: supp, markerId, value, status })
        break
      }
    }
  }
  return out
}
